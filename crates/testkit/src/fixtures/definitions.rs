//! A core-typed definition set modelled on the shop's 68 product metafield definitions
//! (`claude_design/reference/SHOPIFY_PRODUCT_METAFIELDS.md`, read 2026-10-24), each already in its
//! core type (MC-13 type map applied by hand; the adapter's own mapping arrives in P12). Six
//! `test.*` definitions cover the core types the shop has no definition of.

use psm_core::domain::attribute::{AttributeGroup, CoreType, Definition};
use serde_json::{Value, json};

pub const INTEGRATION: &str = "shopify";

const SEVERITY: &[&str] = &["N/A", "None", "Minor", "Moderate", "Major"];

/// Keys starting with this prefix belong to the Condition step (ch08 §Groups and presets).
pub const CONDITION_PREFIX: &str = "custom.condition_";
pub const DAMAGE_REPORT: &str = "custom.damage_report";

fn def(
    key: &str,
    label: &str,
    core_type: CoreType,
    choices: &[&str],
    validations: Value,
) -> Definition {
    let group = if key.starts_with(CONDITION_PREFIX) || key == DAMAGE_REPORT {
        AttributeGroup::Condition
    } else {
        AttributeGroup::Details
    };
    Definition {
        integration: INTEGRATION.into(),
        key: key.into(),
        label: label.into(),
        core_type,
        choices: choices.iter().map(|c| c.to_string()).collect(),
        validations,
        group,
        description: None,
        writable: core_type != CoreType::Reference,
    }
}

